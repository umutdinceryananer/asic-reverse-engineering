import os
import random
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "sim"))
sys.path.insert(0, HERE)
os.chdir(REPO)

import harness                                                  # noqa: E402
