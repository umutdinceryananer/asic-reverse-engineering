"""Easter-egg hunt, domain B1: the output generator's message space, by simulation.

Feeds a battery of 121-bit input vectors to the puzzle's stage-2 netlist
(out/puzzle/netlist.v) under the PDK's own cell models, replicating the framing
`puzzle/example_inputs.vcd` uses for an attempt, and reports every distinct
(success_ever, rendered message) outcome. Any readable rendering that is
neither the TRY AGAIN family nor the winning message is an egg candidate.

Framing, copied from the VCD (out/puzzle/stimulus.txt derives it):

    3 cycles   rst_n=0 enable=0 I=0     the reset toggle the hint asks for
    1 cycle    rst_n=1 enable=0 I=0     idle row between reset and attempt
    121 cycles rst_n=1 enable=1 I=bit   the attempt, one bit per rising edge
    N cycles   the --after row          extension, so the answer can stream out

The cycle model is tools/sim/harness.py's, verbatim: inputs move while the
clock is low, outputs are sampled before the rising edge, one edge per cycle.
The testbench is generated by harness.clocked_bench so this tool cannot drift
from the pipeline's own cycle conventions. Rendering is stage 7's: 0x00 -> \\0,
0x07 -> \\a, 0x0a -> \\n, x/z -> \\?, \\xNN otherwise, nothing dropped; the
trimmed stream runs from the first non-0x00 byte to the last.

--after policies (the policy AND the exact row are printed with every result):

    idle        rst_n=1 enable=0 I=0. The default. This is the row the VCD
                itself drives after each attempt window, and it is byte
                identical to what stage 7's hold-last produced on the winning
                baseline (whose trace ends with this row).
    hold-last   the final attempt row repeated (enable stays 1).
    zeros       every input 0 -- NOTE this holds rst_n low, i.e. reset.
    port=value  overrides applied to the idle row.

Native toolchain only -- `iverilog` and `vvp` as found on PATH, or wherever
GDS_IVERILOG and GDS_VVP point -- with the exact flags tools/sim/harness.py uses (-g2012 -DFUNCTIONAL
-DUNIT_DELAY=#1, model files listed explicitly, -I per cell directory).
No docker, no container. Simulations run sequentially.

Usage:
    .venv-linux/bin/python tools/egg_output_battery.py --selftest
    .venv-linux/bin/python tools/egg_output_battery.py --only 05,06,07
    .venv-linux/bin/python tools/egg_output_battery.py            # full battery
    .venv-linux/bin/python tools/egg_output_battery.py --scratch /tmp/xyz

Writes out/eggs/output_battery.json.
"""

